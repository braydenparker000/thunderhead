const { chromium } = require('playwright');
const S = __dirname;
(async () => {
  const b = await chromium.launch({ args: ['--enable-unsafe-webgpu', '--use-webgpu-adapter=swiftshader'] });
  const ctx = await b.newContext({ viewport: { width: 412, height: 915 }, deviceScaleFactor: 1 });
  const p = await ctx.newPage(); const logs = []; p.on('console', m => logs.push(m.type() + ': ' + m.text())); p.on('pageerror', e => logs.push('ERR ' + e.message));
  p.on('worker', w => w.on('console', m => logs.push('w: ' + m.text())));
  await p.goto((process.env.BASE || 'http://127.0.0.1:8080') + '/'); await p.waitForTimeout(3000);
  await p.goto((process.env.BASE || 'http://127.0.0.1:8080') + '/lab/engine/'); await p.waitForTimeout(3000); await p.setInputFiles('#profiles', S + '/xe5-profiles.zip'); await p.waitForTimeout(2000);
  console.log('engine picker:', await p.evaluate(() => [...document.querySelectorAll('#profile option')].map(o => o.textContent).join(' | ')));
  await p.goto((process.env.BASE || 'http://127.0.0.1:8080') + '/lab/editor/index.html?readback'); await p.waitForTimeout(5000);
  console.log('isolated', await p.evaluate(() => crossOriginIsolated));
  await p.getByRole('button', { name: 'Import' }).click(); await p.waitForTimeout(300);
  const [fc] = await Promise.all([p.waitForEvent('filechooser'), p.getByText('Choose photos').click()]);
  await fc.setFiles([S + '/raf/' + (process.env.FILE || 'Fuji-X-H2-Lossless-Compressed-Raw.RAF')]);
  await p.waitForFunction(() => /Done/.test(document.body.textContent), null, { timeout: 60000 });
  await p.getByRole('button', { name: 'Import' }).click().catch(() => {});
  const t0 = Date.now();
  await p.locator('button[aria-label^="Fuji-X-H2"]').first().click();
  await p.waitForFunction(() => document.querySelector('canvas[aria-label="The photo being edited"]')?.isConnected, null, { timeout: 90000 });
  console.log('developed in', Date.now() - t0, 'ms');
  await p.waitForTimeout(1500); await p.screenshot({ path: S + '/shots/ed9-edit.png' });
  await p.getByRole('button', { name: /Back to the tools/i }).click(); await p.waitForTimeout(400);
  await p.locator('#dock button[data-go="Looks"]').click(); await p.waitForTimeout(500);
  await p.waitForFunction(() => [...document.querySelectorAll('[role=option] img')].filter(i => i.src.startsWith('blob:') && i.naturalWidth && i.naturalWidth < 200).length > 5, null, { timeout: 180000 }).catch(() => console.log('thumbs timeout'));
  await p.waitForTimeout(1500);
  console.log('looks:', await p.evaluate(() => [...document.querySelectorAll('[role=option]')].map(o => o.textContent.trim().replace(/\s+/g, ' ') + (o.getAttribute('aria-selected') === 'true' ? '*' : '')).join(' | ')));
  await p.screenshot({ path: S + '/shots/ed9-looks.png' });
  await p.locator('[role=option]', { hasText: /Adobe Color/ }).first().click(); await p.waitForTimeout(9000);
  await p.screenshot({ path: S + '/shots/ed9-adobe-color.png' });
  console.log('selected:', await p.evaluate(() => [...document.querySelectorAll('[role=option][aria-selected=true]')].map(o => o.textContent.trim()).join(',')));
  console.log(logs.filter(l => !/deprecated/.test(l)).slice(0, 10).join('\n'));
  await b.close();
})();
